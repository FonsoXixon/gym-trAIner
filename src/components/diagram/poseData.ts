export interface AnatomicalPose {
  head: Pt;
  neck: Pt;
  shoulder: Pt;
  hip: Pt;
  // Optional spine midpoint control offset to depict rounded/arched posture in Evita panel!
  spineMid?: Pt;
  // Near limbs (front)
  elbow: Pt;
  hand: Pt;
  knee: Pt;
  foot: Pt;
  // Far limbs (depth layer)
  elbow2?: Pt;
  hand2?: Pt;
  knee2?: Pt;
  foot2?: Pt;
  // Equipment handle / barbell / dumbbell anchor
  bar?: Pt;
  // Working muscle glow center & radius
  glowSpot: [number, number, number];
  // Direction person faces: 1 = right, -1 = left, 0 = up/front
  facing: 1 | -1 | 0;
  // Optional heel lift / body angle hints
  lying?: 'supine' | 'prone';
}

export interface ExerciseDiagramSpec {
  machine: MachineBackdrop;
  start: AnatomicalPose;
  end: AnatomicalPose;
  arrowPath: string;
  // Full-body safety comparison poses (in same 300x192 coordinate space, auto-scaled cleanly!)
  goodPose: AnatomicalPose;
  badPose: AnatomicalPose;
  goodGuidePath: string; // e.g., green straight spine or plumb line
  badGuidePath: string;  // e.g., red curved spine or fault trajectory
  badWarnSpot: Pt;       // pulsing red danger halo on the bad figure
  goodTag: string;       // 2-3 word visual label inside green panel
  badTag: string;        // 2-3 word visual label inside red panel
}

export function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

export function lerpPt(a: Pt, b: Pt, t: number): Pt {
  return [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];
}

export function interpolateAnatomicalPose(
  a: AnatomicalPose,
  b: AnatomicalPose,
  t: number
): AnatomicalPose {
  return {
    head: lerpPt(a.head, b.head, t),
    neck: lerpPt(a.neck, b.neck, t),
    shoulder: lerpPt(a.shoulder, b.shoulder, t),
    hip: lerpPt(a.hip, b.hip, t),
    spineMid: a.spineMid && b.spineMid ? lerpPt(a.spineMid, b.spineMid, t) : undefined,
    elbow: lerpPt(a.elbow, b.elbow, t),
    hand: lerpPt(a.hand, b.hand, t),
    knee: lerpPt(a.knee, b.knee, t),
    foot: lerpPt(a.foot, b.foot, t),
    elbow2: a.elbow2 && b.elbow2 ? lerpPt(a.elbow2, b.elbow2, t) : undefined,
    hand2: a.hand2 && b.hand2 ? lerpPt(a.hand2, b.hand2, t) : undefined,
    knee2: a.knee2 && b.knee2 ? lerpPt(a.knee2, b.knee2, t) : undefined,
    foot2: a.foot2 && b.foot2 ? lerpPt(a.foot2, b.foot2, t) : undefined,
    bar: a.bar && b.bar ? lerpPt(a.bar, b.bar, t) : undefined,
    glowSpot: [
      lerp(a.glowSpot[0], b.glowSpot[0], t),
      lerp(a.glowSpot[1], b.glowSpot[1], t),
      lerp(a.glowSpot[2], b.glowSpot[2], t),
    ],
    facing: a.facing,
    lying: a.lying,
  };
}

